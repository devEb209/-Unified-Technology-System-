		a:ok(cc:detachPlatform("hero"))
		local q = cc:applyQuality(0.1)
		a:equal(q.pushOutIterations, 1)
		a:ok(cc:remove("hero"))
		a:equal(cc:report().controllers, 0)
	end)
end)

