		local dark = {}
		for i = 1, 8 do dark[i] = { 0.02, 0.02, 0.02 } end
		local before = g.averageLuma(dark)
		for _ = 1, 12 do g.autoExpose(dark, 0.18) end
		local after = g.averageLuma(dark)
		a:gt(after, before)
		a:lt(math.abs(after - 0.18), math.abs(before - 0.18))
