t:describe("life/kits", function(s)
	s:it("mindnet decides, learns and exports its weights", function(a)
		local net = Kits.create("mindnet", { id = "m1", inputs = 4, hidden = 4, seed = 7 })
		a:ok(net.addAction("fight"))
		a:ok(net.addAction("flee"))
		a:ok(not net.addAction("fight"))
		local scores = net.forward({ 0.2, 0.8, 0.1, 0.5 })
		a:ok(scores.fight ~= nil and scores.flee ~= nil)
		local action = net.decide({ 0.2, 0.8, 0.1, 0.5 })
		a:ok(action == "fight" or action == "flee")
		-- reinforcing an action must make that action more likely for the same input
		local before = net.actions[action].value
		for _ = 1, 12 do
			net.forward({ 0.2, 0.8, 0.1, 0.5 })
			net.lastAction = action
			net.reinforce(1)
		end
		net.forward({ 0.2, 0.8, 0.1, 0.5 })
		a:gt(net.actions[action].value, before)
		a:gt(net.parameters(), 20)
		local weights = net.exportWeights()
		a:equal(#weights, net.parameters())
		a:equal(net.importWeights(weights), net.parameters())
		a:gt(net.memoryBytes(), 0)
		a:equal(net.resetState(), 4)
		a:gt(net.stats().forwards, 5)
	end)

	s:it("memory decays, recalls and consolidates facts", function(a)
		local mem = Kits.create("memory", { id = "mem", capacity = 5, decayRate = 0.2 })
		mem.remember("danger", { who = "wolf" }, 0.9, v3(10, 0, 0))
		mem.remember("food", { what = "berries" }, 0.4, v3(2, 0, 0))
		a:equal(mem.stats().episodes, 2)
		local danger = mem.recall("danger")
		a:equal(#danger, 1)
		a:equal(danger[1].payload.who, "wolf")
		a:equal(#mem.recallNear(v3(3, 0, 0), 5), 1)
		mem.tick(2)
		a:lt(mem.episodes[2].salience, 0.4)
		-- capacity pressure forgets the weakest memory, not the newest
		for i = 1, 6 do mem.remember("noise", { i = i }, 0.1) end
		a:lte(mem.stats().episodes, 5)
		a:gt(mem.stats().forgotten, 0)
		for _ = 1, 3 do mem.remember("danger", { who = "bear" }, 0.8) end
		a:gt(mem.consolidate(), 0)
		a:ok(mem.knows("danger"))
		a:gt(mem.forget("danger"), 0)
	end)

	s:it("needs decay, become urgent and are satisfied", function(a)
		local needs = Kits.create("need", { id = "n" })
		needs.define("food", { value = 0.5, decay = 0.1, threshold = 0.4 })
		needs.define("rest", { value = 0.9, decay = 0.01, threshold = 0.4 })
		a:near(needs.wellbeing(), 0.7, 0.001)
		a:equal(needs.urgency("food"), 0)
		needs.tick(2)
		a:lt(needs.needs.food.value, 0.4)
		a:gt(needs.urgency("food"), 0)
		local urgent, value = needs.mostUrgent()
		a:equal(urgent, "food")
		a:gt(value, 0)
		needs.satisfy("food", 0.6)
		a:equal(needs.urgency("food"), 0)
		a:equal(#needs.vector(), 2)
		a:gt(needs.stats().satisfactions, 0)
	end)

	s:it("emotion appraises events and settles back to baseline", function(a)
		local emo = Kits.create("emotion", { id = "e" })
		a:equal(emo.label(), "calm")
		emo.appraise(-0.9, 1.0)
		a:lt(emo.valence, 0)
		a:gt(emo.arousal, 0)
		local label = emo.label()
		a:ok(label == "fear" or label == "anger", "a strong bad event must read as fear or anger")
		a:gt(emo.intensity(), 0.3)
		a:lt(emo.mood(), 0)
		local cautious = emo.influence(1)
		a:lt(cautious, 1)
		for _ = 1, 200 do emo.tick(0.1) end
		a:lt(math.abs(emo.valence), 0.05)
		emo.appraise(0.9, 1)
		a:gt(emo.influence(1), 1)
		emo.reset()
