		local far = lib:resolveForDistance("hero", { curvature = 1 }, 900)
		a:lt(far.lod == nil and 0 or far.lod, 99)
		a:gte(far.lod, near.lod)
		a:equal(far.normalStrength, 0, "distant surfaces drop their normals")
		a:ok(lib:bakeDetail("hero", 16) ~= nil)
		a:gte(lib:detailAt("hero", 0.5, 0.5, 0), 0)
		a:ok(lib:attachGraph("hero") ~= nil)
		local src = lib:compileGraph("hero")
		local fn = load(src)
		a:isType(fn, "function")
	end)
end)

