t:describe("kernel/spatial", function(s)
	s:it("aabb intersect + ray", function(a)
		local box = Spatial.aabb(Vec.vec3(0, 0, 0), Vec.vec3(10, 10, 10))
		a:ok(box:contains(Vec.vec3(5, 5, 5)))
		local hit = box:rayHit(Vec.vec3(-5, 5, 5), Vec.vec3(1, 0, 0), 100)
		a:near(hit, 5)
	end)
	s:it("spatial hash radius query", function(a)
		local h = Spatial.spatialHash(10)
		h:insert("a", Vec.vec3(1, 1, 1))
		h:insert("b", Vec.vec3(100, 0, 0))
		local hits = h:queryRadius(Vec.vec3(0, 0, 0), 20)
		a:equal(#hits, 1)
		a:equal(hits[1].id, "a")
	end)
	s:it("octree subdivides and queries", function(a)
		local tree = Spatial.octree(Spatial.aabb(Vec.vec3(0, 0, 0), Vec.vec3(64, 64, 64)), 4, 2)
		for i = 1, 30 do tree:insert("e" .. i, Vec.vec3(i, i % 10, i % 7)) end
		a:gt(tree:nodeCount(), 1)
		local found = tree:query(Spatial.aabb(Vec.vec3(0, 0, 0), Vec.vec3(10, 64, 64)))
		a:gt(#found, 0)
	end)
	s:it("bvh raycast finds nearest", function(a)
		local prims = {}
		for i = 1, 8 do
			prims[i] = { id = i, bounds = Spatial.aabb(Vec.vec3(i * 10, 0, 0), Vec.vec3(i * 10 + 5, 5, 5)) }
		end
		local bvh = Spatial.bvh(prims)
		local hit = bvh:raycast(Vec.vec3(-10, 2, 2), Vec.vec3(1, 0, 0), 500)
		a:equal(hit.id, 1)
	end)
	s:it("frustum culls behind camera", function(a)
		local f = Spatial.frustumFromCamera(Vec.vec3(0, 0, 0), Vec.vec3(0, 0, -1), Vec.vec3(0, 1, 0), math.rad(70), 1.6, 1, 500)
		a:ok(f:containsSphere(Vec.vec3(0, 0, -50), 5))
		a:equal(f:containsSphere(Vec.vec3(0, 0, 50), 1), false)
	end)
end)

