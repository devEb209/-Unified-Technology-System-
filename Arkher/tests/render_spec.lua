t:describe("neural/reconstruction", function(s)
	s:it("trains a policy that lowers scale under load", function(a)
		local R = A:import("arkher/neural/reconstruction")
		local rc = R.new({ targetMs = 16.6 })
		local loss = rc:train(200, 0.35)
		a:lt(loss, 0.05, "the reconstruction policy must actually converge")
		local heavy = rc:predict({ frameMs = 38, motion = 2, complexity = 0.9, battery = 0.4 })
		local light = rc:predict({ frameMs = 8, motion = 2, complexity = 0.2, battery = 1.0 })
		a:lt(heavy.scale, light.scale, "heavier frames must render smaller")
		a:gte(heavy.sharpen, 0)
		local policy = rc:exportPolicy(8)
		a:gt(policy.parameters, 20)
		a:lt(policy.quantError, 0.05)
		local rc2 = R.new({ targetMs = 16.6 })
		a:ok(rc2:importPolicy(policy))
	end)

	s:it("reconstructs, accumulates and recovers from a camera cut", function(a)
		local R = A:import("arkher/neural/reconstruction")
		local rc = R.new({ targetMs = 16.6 })
		rc:train(120, 0.35)
		local before = rc.upscaler.index
		for _ = 1, 6 do rc:apply({ frameMs = 40, motion = 0, complexity = 0.9, battery = 0.5 }) end
		a:lt(rc.upscaler.index, before, "sustained load must walk the ladder down")
		local frame = rc:beginFrame()
		a:gte(frame.frame, 1)
		a:ok(math.abs(frame.jitterX) <= 0.5)
		local line = rc:resolveLine("row", { 0.0, 0.2, 0.8, 1.0 }, 8, { motion = 0 })
		a:equal(#line, 8)
		for _ = 1, 6 do rc:resolveLine("row", { 0.0, 0.2, 0.8, 1.0 }, 8, { motion = 0 }) end
		a:gt(rc:effectiveScale(), rc.upscaler.scale() - 0.001)
		a:gt(rc:quality(), 0)
		a:ok(rc:onCameraCut())
		a:equal(rc.temporal.stats().tracked, 0, "a camera cut must drop the whole history")
		a:gt(rc:report().fallbacks, 0)
	end)
end)

t:describe("render/pipeline", function(s)
	s:it("executes a budgeted frame graph end to end", function(a)
		local Renderer = A:import("arkher/render/renderer")
		local r = Renderer.new({ width = 828, height = 1792, budgetMs = 16.6, tier = "mobile" })
		r.materials:installStandardLibrary()
		for i = 1, 40 do
			r.geometry:add("obj" .. i, { position = v3((i % 8) * 30, 0, math.floor(i / 8) * 30),
				radius = 4, triangles = 3000, material = "concrete" })
		end
		r.geometry:build(2)
		r.lighting:bakeGI(48)
		r:teleportCamera(v3(0, 8, 0), v3(60, 0, 60))
		local frame = r:renderFrame(1 / 60)
		a:gte(#frame.executed, 4)
		a:lte(frame.costMs, 16.6 * 1.25)
		a:gt(frame.triangles, 0)
		a:gt(frame.draws, 0)
		a:gt(frame.scale, 0.3)
		local avg = r:run(20, 1 / 60)
		a:gt(avg, 0)
		a:equal(r.frames, 21)
		local breakdown = r:frameBreakdown()
		a:gt(#breakdown, 4)
		a:gte(breakdown[1].costMs, breakdown[#breakdown].costMs)
		a:ok(r:bottleneck().pass ~= nil)
	end)

	s:it("degrades the whole image stack on one quality call", function(a)
		local Renderer = A:import("arkher/render/renderer")
		local r = Renderer.new({ width = 828, height = 1792, budgetMs = 16.6 })
		for i = 1, 30 do
			r.geometry:add("o" .. i, { position = v3(i * 12, 0, 0), radius = 4, triangles = 5000 })
		end
		r.geometry:build(1)
		local high = r:applyQuality(1.0)
		local hiTri = high.geometry.triangleBudget
		local low = r:applyQuality(0.15)
		a:lt(low.geometry.triangleBudget, hiTri)
		a:lte(low.lighting.shadowBudget, 1)
		a:equal(low.tier, "mobile")
		a:lt(low.scale, 1.0)
