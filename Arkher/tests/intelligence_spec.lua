			if name == "drought-migration" or name == "migration-drought" then hit = true end
		end
		a:ok(hit, "the recurring pair must be named as a phenomenon")
		a:lt(e.novelty("drought"), e.novelty("brand-new"))
		for i = 1, 20 do e.signal("unrest", 0.2) end
		a:near(e.deviation("unrest"), 0, 1e-6)
		e.signal("unrest", 5)
		a:gt(e.deviation("unrest"), 2, "a spike must show as a deviation")
