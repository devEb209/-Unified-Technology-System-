		a:gt(count, 0)
		local docs = intel:generateDocs("main.lua")
		a:ok(string.find(docs, "bootstrap") ~= nil)
	end)
	s:it("detects unbalanced code as an error", function(a)
		intel:index("broken.lua", "local function x() if true then return 1 end")
		local diags = intel:analyze("broken.lua")
		local hasError = false
		for _, d in ipairs(diags) do if d.severity == "error" then hasError = true end end
		a:ok(hasError)
	end)
end)

