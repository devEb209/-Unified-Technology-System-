		soc.setFactionStanding("north", "south", -0.8)
		a:lt(soc.disposition("ana", "cy"), 0)
		soc.interact("bo", "cy", 1, 0.6)
		local reached = soc.gossip("ana", "cy", -1)
		a:gte(reached, 1)
		a:lt(soc.members.cy.reputation, 0)
		a:equal(#soc.friendsOf("ana", 0.3), 1)
		a:gt(soc.cohesion(), 0)
		soc.tick(10)
		a:gt(soc.stats().interactions, 1)
	end)

	s:it("economy moves prices with supply and demand", function(a)
		local eco = Kits.create("economy", { id = "eco", elasticity = 0.5 })
		eco.defineGood("grain", { basePrice = 10 })
		eco.addMarket("farm", { wealth = 500 })
		eco.addMarket("city", { wealth = 900 })
		eco.setStock("farm", "grain", 400)
		eco.setStock("city", "grain", 5)
		eco.setProduction("farm", "grain", 8)
		eco.setDemand("city", "grain", 6)
		local cheap = eco.priceOf("grain")
		for _ = 1, 20 do eco.tick(0.5) end
		a:gt(eco.totalStock("grain"), 0)
		a:gt(eco.stats().produced, 0)
		a:gt(eco.stats().consumed, 0)
		local moved, price = eco.trade("farm", "city", "grain", 50)
		a:gt(moved, 0)
		a:gt(price, 0)
		a:gt(eco.markets.city.stock.grain, 5)
		a:lt(eco.markets.city.wealth, 900)
		a:gt(eco.balance(), -1)
		a:gt(eco.stats().trades, 0)
		a:ok(cheap > 0)
	end)

	s:it("schedule runs a day and yields to interruptions", function(a)
		local sc = Kits.create("schedule", { id = "sc", startHour = 7 })
		sc.addSlot("sleep", 22, 6, { priority = 3 })
		sc.addSlot("work", 8, 17, { priority = 2, location = v3(10, 0, 0) })
		sc.addSlot("rest", 17, 22, { priority = 1 })
		a:equal(sc.activeAt(9).activity, "work")
		a:equal(sc.activeAt(23).activity, "sleep")
		a:equal(sc.activeAt(2).activity, "sleep")
		local activity = sc.advance(2)
		a:equal(activity, "work")
		a:equal(sc.stats().hour, 9)
		sc.interrupt("flee", 1, 10)
		a:equal(sc.advance(0.25), "flee")
		sc.advance(1.5)
		a:equal(sc.stats().current, "work")
		a:ok(sc.locationFor("work") ~= nil)
		sc.advance(14)
		a:ok(sc.isNight())
		a:gt(sc.stats().changes, 1)
	end)

	s:it("ecology grows populations and couples predator to prey", function(a)
		local eco = Kits.create("ecology", { id = "bio" })
		eco.addSpecies("deer", { population = 200, growth = 0.3, capacity = 800 })
		eco.addSpecies("wolf", { population = 20, growth = -0.1, capacity = 90 })
		eco.link("wolf", "deer", { predation = 0.001, efficiency = 0.4 })
		local startDeer = eco.populationOf("deer")
		for _ = 1, 40 do eco.step(0.5) end
		a:gt(eco.populationOf("deer"), startDeer)
		a:gt(eco.biomass(), 200)
		-- remove the prey and the predator must collapse
		eco.harvest("deer", eco.populationOf("deer"))
		for _ = 1, 200 do eco.step(0.5) end
		a:lt(eco.populationOf("wolf"), 20)
		a:gt(eco.stats().harvested, 0)
		eco.seed("deer", 150)
		a:gt(eco.populationOf("deer"), 100)
		for _ = 1, 400 do eco.step(0.25) end
		a:gte(eco.stats().ticks, 600)
	end)
end)

