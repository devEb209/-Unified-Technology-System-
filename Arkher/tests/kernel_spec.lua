		sch.stats.a.avgMs = 20
		sch.stats.b.avgMs = 5
		local disabled = sch:degradeToBudget(10)
		a:equal(disabled[1], "a")
	end)
end)

t:describe("kernel/jobsystem", function(s)
	s:it("runs cooperative jobs to completion", function(a)
		local js = JobSystem.new({ workers = 2, timeFn = function() return 0 end })
		local acc = 0
		local job = js:schedule(function(yield)
			for i = 1, 5 do acc = acc + i yield() end
			return acc
		end)
		js:drain()
		a:equal(job.state, "done")
		a:equal(acc, 15)
	end)
	s:it("parallelFor covers the whole range", function(a)
		local js = JobSystem.new({ workers = 4, timeFn = function() return 0 end })
		local hits = {}
		js:parallelFor(1, 100, 10, function(i) hits[i] = true end)
		js:drain()
		local count = 0
		for i = 1, 100 do if hits[i] then count = count + 1 end end
		a:equal(count, 100)
		a:equal(js:stats().completed, 10)
	end)
end)

t:describe("kernel/promise", function(s)
