	s:it("camerarig frames, focuses and settles toward its target", function(a)
		local rig = Kits.create("camerarig", { id = "rig", mode = "orbit",
			distance = 10, height = 4, smoothing = 12 })
		local subject = v3(0, 0, 0)
		local first = rig.update(1 / 30, subject)
		local firstDistance = first:distance(subject)
		for _ = 1, 120 do rig.update(1 / 30, subject) end
		local settled = rig.position:distance(subject)
		a:lt(math.abs(settled - math.sqrt(10 * 10 + 4 * 4)), math.abs(firstDistance - 10) + 2)
		a:near(rig.focus, settled, 1e-6, "focus must follow the subject")
		a:near(rig.circleOfConfusion(rig.focus), 0, 1e-6)
		a:gt(rig.circleOfConfusion(rig.focus * 4), 0)
		local near = rig.frameSubject(2, 0.5)
		local wide = rig.frameSubject(2, 0.25)
		a:gt(wide, near, "a smaller screen fraction must pull the camera back")
		rig.shake(1)
		rig.update(0.1, subject)
		a:lt(rig.shakeAmount, 1, "shake must decay")
		rig.setMode("dolly")
		rig.addPathPoint(v3(0, 0, 0))
		rig.addPathPoint(v3(10, 0, 0))
		a:near(rig.pathAt(0.5).x, 5, 1e-6)
		a:near(rig.pathLength, 10, 1e-6)
