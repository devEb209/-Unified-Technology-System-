		local res, err = sb:invoke("plugin.x", "scene.write", function() return true end)
		a:equal(res, nil)
		a:equal(err.codeName, "SANDBOX_VIOLATION")
		sb:grant("plugin.x", "scene.write")
		a:equal(sb:invoke("plugin.x", "scene.write", function() return "ok" end), "ok")
	end)
	s:it("applies roles and wildcards", function(a)
		local sb = Sandbox.new()
		sb:createPrincipal("ai.agent")
		sb:applyRole("ai.agent", "admin")
		a:ok(sb:can("ai.agent", "scene.destroy"))
		a:equal(sb:can("ai.agent", "filesystem.write"), false)
	end)
	s:it("enforces per-frame quota", function(a)
		local sb = Sandbox.new()
		local p = sb:createPrincipal("spam", { quota = { calls = 1000, perFrame = 3 } })
		sb:grant("spam", "scene.read")
		for _ = 1, 3 do sb:invoke("spam", "scene.read", function() end) end
		local _, err = sb:invoke("spam", "scene.read", function() end)
		a:equal(err.codeName, "RESOURCE_EXHAUSTED")
		sb:resetFrameQuotas()
		a:equal(select(2, sb:invoke("spam", "scene.read", function() end)), nil)
	end)
	s:it("detects corruption and recovers", function(a)
		local ig = Integrity.new()
		local state = { level = 1, items = { "a", "b" } }
		ig:checkpoint("start", state)
		local recovered = ig:recover()
		a:equal(recovered.level, 1)
		ig:sign("doc", { v = 1 })
		a:ok(ig:verify("doc", { v = 1 }))
		a:equal(ig:verify("doc", { v = 2 }), false)
