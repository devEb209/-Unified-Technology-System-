	s:it("worldmemory recalls, compacts, checkpoints and restores", function(a)
		local m = Kits.create("worldmemory", { id = "m", capacity = 8 })
		m.remember("ana", "born", { region = "north" })
		m.advance(1)
		m.remember("ana", "moved", { region = "south", weight = 2 })
		m.remember("bob", "born", { region = "north" })
		a:equal(#m.recall({ subject = "ana" }), 2)
		a:equal(#m.recall({ region = "north" }), 2)
		a:equal(#m.recall({ since = 0.5 }), 2)
		a:equal(#m.historyOf("ana"), 2)
		local epoch = m.advanceEpoch("age-of-steel")
		a:equal(epoch, 2)
		m.remember("bob", "built", { region = "north" })
		a:equal(#m.recall({ epoch = 2 }), 1)
		local cp = m.checkpoint("save1")
		m.remember("bob", "died", {})
		a:ok(m.checksum() ~= cp.checksum)
		a:ok(m.restore(cp), "restoring must reproduce the exact checksum")
		a:equal(#m.recall({ subject = "bob" }), 2)
		for i = 1, 12 do m.remember("crowd", "step" .. (i % 3), {}) end
		a:lte(#m.records, 12)
		a:gt(m.stats().compacted, 0, "overflow must fold into summaries")
		a:ok(m.summaryOf("ana", "born") ~= nil or m.summaryOf("crowd", "step1") ~= nil)
	end)

