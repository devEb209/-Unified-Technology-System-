t:describe("animation/motion_matching", function(s)
	s:it("builds a database and matches the best frame", function(a)
		local Animation = A:import("arkher/animation/animation_system")
		local MM = A:import("arkher/animation/motion_matching")
		local an = Animation.new({})
		an:buildLocomotionSet({ "hips", "LFoot", "RFoot" })
		local mm = MM.new({ minInterval = 0 })
		local idle = mm:buildFromClip("idle", an.clips.idle, { rate = 8, speed = 0 })
		local run = mm:buildFromClip("run", an.clips.run, { rate = 8, speed = 6 })
		a:gt(idle, 5)
		a:gt(run, 3)
		a:equal(mm:report().clips, 2)
		local fast = mm:queryFromMotion(v3(0, 0, 6), v3(0, 0, 1))
		local result = mm:update(1 / 60, fast)
		a:ok(result.searched)
		a:equal(result.clip, "run")
		local still = mm:queryFromMotion(v3(), v3(0, 0, 1))
		for _ = 1, 6 do result = mm:update(1 / 60, still) end
		a:equal(result.clip, "idle")
		a:gt(mm:report().switches, 0)
		a:gt(mm:report().comparisons, 10)
	end)

	s:it("respects the search budget and blends poses", function(a)
		local Animation = A:import("arkher/animation/animation_system")
		local MM = A:import("arkher/animation/motion_matching")
		local an = Animation.new({})
		an:buildLocomotionSet({ "hips" })
		local mm = MM.new({ minInterval = 0.1 })
		mm:buildFromClip("walk", an.clips.walk, { rate = 60, speed = 1.6 })
		a:gt(#mm.frames, 50)
		local low = mm:applyQuality(0.0)
		a:lt(low.searchBudget, 200)
		mm.searchBudget = 8
		local before = mm.comparisons
		mm:update(1, mm:queryFromMotion(v3(0, 0, 1.6), v3(0, 0, 1)))
		a:lte(mm.comparisons - before, 16)
		local skipped = mm:update(1 / 60, mm:queryFromMotion(v3(), v3(0, 0, 1)))
		a:ok(not skipped.searched, "searches must be throttled by minInterval")
		a:ok(mm:currentPose() ~= nil)
	end)
end)

t:describe("character/digital_human", function(s)
	s:it("spawns a full digital human and drives its state machine", function(a)
