		local report = lib:report()
		a:gt(report.materials, 15)
		a:gt(report.memoryBytes, 0)
		a:equal(lib:checksum(), lib:checksum())
	end)

	s:it("enforces tiers, lods and compaction", function(a)
		local MF = A:import("arkher/materials/material_framework")
		local lib = MF.new({ tier = "mobile" })
		lib:define("hero", { preset = "steel", priority = 1 })
