t:describe("kernel/resource + profiler + version", function(s)
	s:it("streams resources under budget", function(a)
		local rm = Resource.new({ budgetBytes = 1000 })
		rm:registerLoader("mesh", function(id) return { id = id }, 400 end)
		rm:declare("m1", "mesh")
		rm:declare("m2", "mesh")
		rm:declare("m3", "mesh")
		rm:request("m1", 5) rm:request("m2", 3) rm:request("m3", 1)
		rm:pump(3)
		a:equal(rm:state("m1"), "loaded")
		a:gt(rm:memoryPressure(), 1.0)
		rm:release("m1") rm:release("m2") rm:release("m3")
		rm:enforceBudget()
		a:lt(rm.usedBytes, 1001)
	end)
	s:it("object pool reuses", function(a)
		local created = 0
		local pool = Resource.pool(function() created = created + 1 return { alive = true } end, function(o) o.alive = false end, 2)
		local o = pool:acquire()
		pool:release(o)
		local o2 = pool:acquire()
		a:equal(created, 2)
		a:equal(pool:stats().live, 1)
	end)
	s:it("profiler measures scopes", function(a)
		local time = 0
