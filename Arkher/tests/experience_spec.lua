	s:it("spatial audio attenuates, pans and culls", function(a)
		local sa = Kits.create("spatialaudio", { id = "sa", refDistance = 5,
			maxDistance = 100, maxVoices = 2 })
		sa.setListener(v3(), v3(0, 0, -1), v3(0, 1, 0))
		sa.addSource("near", v3(0, 0, 5), { volume = 1, priority = 1 })
		sa.addSource("right", v3(20, 0, 0), { volume = 1, priority = 1 })
		sa.addSource("far", v3(0, 0, 95), { volume = 1, priority = 1 })
		a:equal(sa.gainOf("near"), 1)
		a:lt(sa.gainOf("far"), 0.2)
		a:gt(sa.pan(v3(20, 0, 0)), 0.9)
		a:lt(sa.pan(v3(-20, 0, 0)), -0.9)
		sa.setOcclusion("near", 1)
		a:lt(sa.gainOf("near"), 0.3)
		sa.setOcclusion("near", 0)
		-- moving toward the listener raises the pitch, away lowers it
		sa.moveSource("right", v3(20, 0, 0), v3(-30, 0, 0))
		a:gt(sa.doppler("right"), 1)
		sa.moveSource("right", v3(20, 0, 0), v3(30, 0, 0))
		a:lt(sa.doppler("right"), 1)
		local live = sa.cullVoices()
		a:equal(#live, 2)
		a:gt(sa.stats().culled, 0)
		local mix = sa.mixSnapshot()
		a:equal(#mix, 2)
		a:ok(mix[1].gain >= mix[2].gain)
	end)

