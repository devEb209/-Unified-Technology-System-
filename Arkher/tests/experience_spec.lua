		a:equal(audio.music.stats().current, "combat")
		a:gt(audio.music.layerGain("percussion"), 0.3)
		local low = audio:applyQuality(0.1)
		a:lte(low.maxVoices, 24)
		a:gt(audio:report().time, 4)
	end)
end)

