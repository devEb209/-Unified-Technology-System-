		civ:found("harbor", { position = v3(0, 0, 0), population = 400,
			specialties = { "food", "wood" }, faction = "crown", prosperity = 0.7 })
		civ:found("mine", { position = v3(300, 0, 0), population = 150,
			specialties = { "ore" }, faction = "crown", prosperity = 0.3, unrest = 0.4 })
		a:equal(civ:report().settlements, 2)
		a:ok(civ:connect("harbor", "mine", { danger = 0.1 }) ~= nil)
		a:ok(civ:routeBetween("mine", "harbor") ~= nil)
		local path = civ:tradePath("harbor", "mine")
		a:ok(path ~= nil)
		civ:run(20, 0.25)
		a:gt(civ.routes[1].volume, 0, "a connected route must actually move goods")
		a:gt(civ.migrations, 0, "people must move toward the better place")
		a:gt(civ:settlement("harbor").population, 400)
		a:lt(civ:settlement("mine").population, 150)
		a:equal(select(1, civ:largest()), "harbor")
	end)

	s:it("laws, wars and revolts change the numbers", function(a)
		local Civ = A:import("arkher/sim/civilization")
		local civ = Civ.new({ seed = 8 })
		civ:found("north", { position = v3(), population = 300, faction = "north" })
		civ:found("south", { position = v3(400, 0, 0), population = 300, faction = "south" })
		local before = civ:settlement("north").safety
		a:ok(civ:enact("north", "curfew") ~= nil)
		a:gt(civ:settlement("north").safety, before)
		a:equal(civ:enact("north", "curfew"), nil)
		a:ok(civ:repeal("north", "curfew"))
		a:near(civ:settlement("north").safety, before, 0.001)
		a:ok(civ:declareWar("north", "south"))
		a:ok(civ:atWar("north", "south"))
		local safety = civ:settlement("north").safety
		civ:run(10, 0.5)
		a:lt(civ:settlement("north").safety, safety)
		a:ok(civ:makePeace("north", "south"))
		a:ok(not civ:atWar("north", "south"))
