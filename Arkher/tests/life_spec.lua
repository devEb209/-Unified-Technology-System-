	s:it("perception sees, hears and keeps a bounded attention list", function(a)
		local p = Kits.create("perception", { id = "p", sightRange = 30,
			hearingRange = 10, attentionSlots = 2 })
		p.place(v3(), v3(0, 0, 1))
		a:ok(p.canSee(v3(0, 0, 10)))
		a:ok(not p.canSee(v3(0, 0, -10)), "nothing behind the head is visible")
		a:ok(not p.canSee(v3(0, 0, 200)))
		a:ok(p.canSee(v3(0, 0, 10), true) == false, "occlusion blocks sight")
		a:ok(p.canHear(v3(0, 0, -8), 1))
		p.submit("near", v3(0, 0, 4), { threat = 0.9, intensity = 0.9 })
		p.submit("far", v3(0, 0, 25), { intensity = 0.2 })
		p.submit("behind", v3(0, 0, -50))
		local attention, perceived = p.scan()
		a:equal(#attention, 2)
		a:equal(attention[1].id, "near")
		a:equal(perceived, 2)
		a:equal(p.focus().id, "near")
		a:gt(p.stats().ignored, 0)
		a:equal(p.clear(), 3)
	end)

	s:it("behaviour tree selects, sequences and respects cooldowns", function(a)
		local bt = Kits.create("behaviortree", { id = "bt" })
		bt.addNode("root", "selector")
		bt.addNode("guard", "sequence")
		bt.addNode("isThreat", "condition",
			{ condition = function(bb) return bb.threat == true end })
		bt.addNode("fight", "action", { action = function(bb) bb.did = "fight" return "success" end })
		bt.addNode("idle", "action", { action = function(bb) bb.did = "idle" return "success" end })
		bt.attach("root", "guard")
		bt.attach("guard", "isThreat")
		bt.attach("guard", "fight")
		bt.attach("root", "idle")
		bt.set("threat", false)
		a:equal(bt.tick(0.1), "success")
		a:equal(bt.get("did"), "idle")
		bt.set("threat", true)
		bt.tick(0.1)
		a:equal(bt.get("did"), "fight")
		a:equal(bt.depth(), 3)
		-- an inverter flips its child, a cooldown blocks repeats
		bt.addNode("never", "inverter")
		bt.addNode("always", "action", { action = function() return "success" end })
		bt.attach("never", "always")
		bt.setRoot("never")
		a:equal(bt.tick(0.1), "failure")
		bt.addNode("throttle", "cooldown", { cooldown = 1 })
		bt.attach("throttle", "always")
		bt.setRoot("throttle")
		a:equal(bt.tick(0.1), "success")
		a:equal(bt.tick(0.1), "failure")
		bt.tick(1.2)
		a:gt(bt.stats().ticks, 4)
	end)

	s:it("utility scores options with response curves", function(a)
		local u = Kits.create("utility", { id = "u", momentum = 0 })
		u.addOption("eat")
		u.addConsideration("eat", "hunger", function(ctx) return 1 - ctx.food end, "quadratic")
		u.addOption("sleep")
		u.addConsideration("sleep", "tired", function(ctx) return 1 - ctx.energy end, "linear")
		local hungry = { food = 0.05, energy = 0.9 }
		a:equal(u.evaluate(hungry, 0), "eat")
		local tired = { food = 0.95, energy = 0.05 }
		a:equal(u.evaluate(tired, 0), "sleep")
		local ranking = u.ranking(tired)
		a:equal(ranking[1].name, "sleep")
		a:gt(ranking[1].score, ranking[2].score)
		-- a cooldown takes an option out of the running
		u.options.sleep.cooldown = 5
		u.evaluate(tired, 0)
		a:equal(u.evaluate(tired, 0.1), "eat")
		a:gt(u.stats().evaluations, 3)
	end)

	s:it("planner builds a GOAP plan and proves it works", function(a)
		local p = Kits.create("planner", { id = "goap" })
		p.addAction("chop", { pre = { hasAxe = true }, effects = { hasWood = true }, cost = 2 })
		p.addAction("getAxe", { pre = { hasAxe = false }, effects = { hasAxe = true }, cost = 1 })
		p.addAction("build", { pre = { hasWood = true }, effects = { hasShelter = true }, cost = 3 })
		local plan, cost = p.plan({ hasAxe = false, hasWood = false, hasShelter = false },
			{ hasShelter = true })
		a:ok(plan ~= nil)
		a:equal(#plan, 3)
		a:equal(plan[1], "getAxe")
		a:equal(plan[3], "build")
		a:equal(cost, 6)
		local final, ok = p.simulate({ hasAxe = false, hasWood = false, hasShelter = false }, plan)
		a:ok(ok)
		a:equal(final.hasShelter, true)
		a:equal(p.planCost(plan), 6)
		local impossible = p.plan({ hasAxe = false }, { hasCastle = true })
		a:equal(impossible, nil)
		a:gt(p.stats().expansions, 2)
	end)

	s:it("navgraph finds, smooths and flows paths around obstacles", function(a)
		local nav = Kits.create("navgraph", { id = "nav", width = 20, height = 20, cellSize = 2 })
		a:ok(nav.walkable(5, 5))
		a:equal(nav.blockRect(5, 0, 5, 15), 16)
		a:ok(not nav.walkable(5, 5))
		local path, cost = nav.findPath(1, 1, 12, 1)
		a:ok(path ~= nil, "a path must exist around the wall")
		a:gt(cost, 11)
		a:gt(#path, 11)
		-- the path must actually go around: some node passes the wall's end
		local maxZ = 0
		for _, node in ipairs(path) do
			if node.z > maxZ then maxZ = node.z end
		end
		a:gt(maxZ, 14)
		local smoothed = nav.smooth(path)
		a:lt(#smoothed, #path)
		a:equal(#nav.worldPath(smoothed), #smoothed)
		a:gt(nav.pathLength(path), 0)
		a:ok(not nav.lineOfSight(1, 1, 12, 1))
		a:ok(nav.lineOfSight(1, 1, 4, 4))
		local field = nav.flowField(12, 1)
		local dir = field.direction(1, 1)
		a:ok(dir:length() > 0)
		a:equal(nav.findPath(5, 5, 12, 1), nil)
		a:gt(nav.stats().expansions, 20)
	end)

	s:it("crowd steers agents to targets without overlapping", function(a)
		local crowd = Kits.create("crowd", { id = "c", maxSpeed = 6 })
		for i = 1, 8 do
			crowd.add("a" .. i, v3(i * 1.5, 0, 0), {})
			crowd.setTarget("a" .. i, v3(30, 0, i * 0.2))
		end
		for _ = 1, 240 do crowd.step(1 / 30) end
		a:gt(crowd.arrivedCount(), 4)
		a:gt(crowd.stats().steps, 200)
		-- no two agents may end the run occupying the same spot
		local overlaps = 0
		for i = 1, 8 do
			for j = i + 1, 8 do
				local d = crowd.agents["a" .. i].position:distance(crowd.agents["a" .. j].position)
				if d < 0.4 then overlaps = overlaps + 1 end
			end
		end
		a:equal(overlaps, 0)
		a:gt(crowd.stats().neighborChecks, 0)
		a:ok(crowd.remove("a1"))
		a:equal(crowd.stats().agents, 7)
	end)

	s:it("society tracks relations, factions and gossip", function(a)
