t:describe("collab/workspace + build", function(s)
	local ws
	s:it("collaborates with locks and presence", function(a)
		ws = Workspace.new({ initial = { objects = {} } })
		ws:join("ana", "editor")
		ws:join("bob", "editor")
		a:ok(ws:lock("ana", "objects.tower"))
		a:ok(ws:edit("ana", "objects.tower", { height = 40 }))
		local ok = ws:edit("bob", "objects.tower", { height = 10 })
		a:equal(ok, false)
		ws:unlock("ana", "objects.tower")
		a:ok(ws:edit("bob", "objects.tower", { height = 12 }))
		a:equal(#ws:sync(0), 2)
		a:gt(ws:comment("ana", "objects.tower", "too short"), 0)
	end)
	s:it("commits, branches and merges without conflict", function(a)
		local c1 = ws:commit("ana", "initial")
		a:ok(c1 ~= nil)
		ws:branch("feature")
		ws:checkout("feature")
		ws:join("cid", "editor")
		ws:edit("cid", "objects.bridge", { span = 100 })
		ws:commit("cid", "add bridge")
		ws:checkout("main")
		ws:edit("ana", "objects.road", { length = 500 })
		ws:commit("ana", "add road")
		local merged, conflicts = ws:merge("feature", "ana")
		a:ok(merged ~= nil, tostring(conflicts))
		a:ok(ws.workingTree.objects.bridge ~= nil)
		a:ok(ws.workingTree.objects.road ~= nil)
		a:gte(#ws:history("main"), 3)
	end)
	s:it("runs an incremental build pipeline with gates", function(a)
		local b = Build.new({})
		b:standardPipeline({ name = "demo", version = "1.0.0", assetCount = 12, fileCount = 40,
			testsPassed = 87, testsFailed = 0, assetBytes = 1000000, channel = "release" })
		b:addGate("tests-must-pass", function(ctx) return (ctx.failed or 0) == 0, "tests failing" end)
		b:addGate("size-limit", function(ctx) return (ctx.sizeMB or 0) < 100, "bundle too large" end)
		local report = b:run()
		a:equal(report.error, nil)
		a:gte(#report.executed, 7)
		local report2 = b:run()
		a:equal(#report2.executed, 0, "everything should be cached")
		a:ok(b:checkGates({ failed = 0, sizeMB = 20 }))
		local ok, blocked = b:checkGates({ failed = 3, sizeMB = 20 })
		a:equal(ok, false)
		a:equal(#blocked, 1)
		b:invalidate("run.tests")
		a:gte(#b:run().executed, 1)
	end)
end)

