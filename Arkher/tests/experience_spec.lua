			interestRadius = 50, fullEvery = 10 })
		rep.spawn("a", { hp = 100, name = "ana" }, v3(0, 0, 0))
		rep.spawn("b", { hp = 80, name = "bo" }, v3(40, 0, 0))
		rep.spawn("far", { hp = 50, name = "zed" }, v3(400, 0, 0))
