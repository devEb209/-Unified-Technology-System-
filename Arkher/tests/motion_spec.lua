		local entry = cc:add("hero", { position = v3(0, 0.5, 0) })
		a:ok(entry ~= nil)
		local grounded = cc:probeGround("hero")
		a:ok(grounded, "the floor must be found under the capsule")
		for _ = 1, 60 do cc:update("hero", v3(1, 0, 0), 1 / 60) end
		a:gt(entry.motor.position.x, 0.5)
		a:gt(cc.sweeps, 0)
		-- a body overlapping the capsule is pushed away
		w:addBody("blocker", { position = entry.motor.position + v3(0.1, 0, 0),
			mass = 0, radius = 0.5 })
		local pushed = cc:pushOut("hero")
		a:gt(pushed, 0)
		a:gt(cc.depenetrations, 0)
		local report = cc:report()
		a:equal(report.controllers, 1)
		a:gt(report.sweeps, 0)
	end)

	s:it("buffers jumps, rides platforms and scales quality", function(a)
		local World = A:import("arkher/physics/world")
		local CC = A:import("arkher/physics/character_controller")
		local w = World.new({})
		local cc = CC.new(w, {})
		local entry = cc:add("hero", { position = v3(0, 5, 0) })
		entry.motor.setGround(false)
		a:ok(not cc:requestJump("hero") or entry.motor.jumps > 0)
		w:addBody("lift", { position = v3(0, 0, 0), mass = 0, shape = "box",
			halfExtents = v3(2, 0.5, 2) })
		entry.motor.position = v3(0, 1, 0)
		a:ok(cc:attachPlatform("hero", "lift"))
		w.bodies.lift.teleport(v3(4, 0, 0))
		cc:followPlatform("hero")
