t:describe("kernel/signal + eventbus", function(s)
	s:it("fires in priority order and disconnects", function(a)
		local sig = Signal.new("t")
		local seen = {}
		sig:connect(function() seen[#seen + 1] = "low" end, 0)
		local c = sig:connect(function() seen[#seen + 1] = "high" end, 10)
		sig:fire()
		a:equal(seen[1], "high")
		c:disconnect()
		sig:fire()
		a:equal(sig:count(), 1)
	end)
	s:it("routes wildcard topics and defers", function(a)
		local bus = EventBus.new()
		local hits = 0
		bus:subscribe("world.*", function() hits = hits + 1 end)
		bus:publish("world.chunk.loaded", {})
		bus:post("world.entity.spawned", {})
		a:equal(hits, 1)
		bus:flush()
		a:equal(hits, 2)
		a:equal(bus:stats().published, 2)
	end)
end)

t:describe("kernel/scheduler", function(s)
	s:it("runs phases with intervals", function(a)
		local time = 0
		local sch = Scheduler.new({ timeFn = function() return time end })
		local n = 0
		sch:add({ id = "tick", phase = Scheduler.Phase.SIMULATION, fn = function() n = n + 1 end })
		sch:add({ id = "slow", phase = Scheduler.Phase.AI, interval = 1.0, fn = function() n = n + 100 end })
		sch:frame(0.1)
