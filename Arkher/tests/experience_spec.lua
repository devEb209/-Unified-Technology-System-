t:describe("audio/engine", function(s)
	s:it("plays, mixes and finishes voices", function(a)
		local Audio = A:import("arkher/audio/audio_engine")
		local audio = Audio.new({ maxVoices = 8 })
		audio:define("step", { bus = "sfx", length = 0.4, volume = 0.8 })
		audio:define("theme", { bus = "music", length = 30, loop = true, spatial = false })
		audio:setListener(v3(), v3(0, 0, -1), v3(0, 1, 0))
		local voice = audio:play("step", v3(0, 0, 3))
		a:ok(voice ~= nil)
		a:ok(audio:isPlaying(voice))
		a:gt(audio:gainOf(voice), 0)
		local music = audio:play("theme")
		a:gt(audio:gainOf(music), 0)
		audio:run(1.0, 1 / 30)
		a:ok(not audio:isPlaying(voice), "a one-shot must end on its own")
		a:ok(audio:isPlaying(music), "a loop must keep going")
		a:equal(audio:report().played, 2)
	end)

	s:it("spatialises, ducks and steals voices under pressure", function(a)
		local Audio = A:import("arkher/audio/audio_engine")
		local audio = Audio.new({ maxVoices = 3 })
		audio:define("bang", { bus = "sfx", length = 5, priority = 1 })
		audio:define("line", { bus = "voice", length = 5, priority = 9 })
		audio:setListener(v3(), v3(0, 0, -1), v3(0, 1, 0))
		local near = audio:play("bang", v3(0, 0, 4), { id = "near" })
		local far = audio:play("bang", v3(0, 0, 90), { id = "far" })
		a:gt(audio:gainOf(near), audio:gainOf(far))
		local right = audio:play("bang", v3(30, 0, 0), { id = "right" })
		a:gt(audio:panOf(right), 0.8)
		a:ok(audio:play("bang", v3(), { id = "extra" }) == nil, "a full mixer refuses a voice")
		local dialogue = audio:play("line", v3(0, 0, 1), { id = "line1" })
		a:ok(dialogue ~= nil, "an important voice steals a slot")
		audio:duckFor("sfx", 0.9, 0.5)
		audio:run(0.4, 1 / 30)
		a:lt(audio.mixer.effectiveGain("sfx"), 0.4, "dialogue must push the effects down")
		audio:run(1.5, 1 / 30)
		a:gt(audio.mixer.effectiveGain("sfx"), 0.4, "ducking must release")
		local loudest = audio:loudest()
		a:ok(loudest ~= nil)
	end)

	s:it("runs adaptive music with stems and quantized transitions", function(a)
		local Audio = A:import("arkher/audio/audio_engine")
