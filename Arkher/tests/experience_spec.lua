		local em = Kits.create("emitter", { id = "e", shape = "cone", rate = 60,
			speed = 10, life = 1, budget = 40, seed = 5 })
		local first = em.emit(0.5, 0)
		a:equal(#first, 30)
		a:equal(em.stats().emitted, 30)
		em.burst(10, 0.5)
		local second = em.emit(0.1, 0)
		a:gte(#second, 10)
		-- the budget is a hard ceiling: nothing is emitted into a full system
		local blocked = em.emit(1, 40)
		a:equal(#blocked, 0)
		a:gt(em.stats().dropped, 0)
		local spec = em.sampleSpec()
		a:ok(spec.position ~= nil and spec.velocity ~= nil)
		a:gt(spec.velocity:length(), 0)
		a:gt(spec.life, 0)
		em.setShape("sphere", { radius = 3 })
		local p = em.samplePosition()
		a:lte(p:length(), 3.001)
		em.pause()
		a:equal(#em.emit(1, 0), 0)
		em.resume()
		local low = em.applyQuality(0.1)
		a:lt(low.budget, 40)
	end)

