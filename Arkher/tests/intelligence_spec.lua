	s:it("intent parses a real sentence into an actionable structure", function(a)
		local intent = Kits.create("intent", { id = "i" })
		local r = intent.parse("build a realistic city with 120 buildings for weak phones")
		a:equal(r.action, "create")
		a:equal(r.target, "city")
		a:equal(r.quantity, 120)
		a:equal(r.constraints.device, "mobile")
		a:ok(r.understood)
		a:gt(r.confidence, 0.3)
		local found = false
		for _, q in ipairs(r.qualifiers) do
			if q == "realistic" then found = true end
		end
		a:ok(found, "the qualifier must survive parsing")
		-- an unrelated sentence must NOT be claimed as understood
		local noise = intent.parse("zzz qqq")
		a:ok(not noise.understood)
		a:equal(intent.stats().unmatched, 1)
		a:ok(intent.explain(r):find("city") ~= nil)
	end)

	s:it("intent recovers the action from context when no verb is spoken", function(a)
		local intent = Kits.create("intent", { id = "i2" })
		local r = intent.parse("the map is slow and the fps drops on phones")
		a:equal(r.action, "optimize")
		a:equal(r.constraints.device, "mobile")
		a:gt(intent.vocabulary().verbs, 3)
	end)

	s:it("knowledge infers transitive dependencies and finds a path", function(a)
		local k = Kits.create("knowledge", { id = "k" })
		k.addEntity("terrain", "system")
		k.addEntity("roads", "system")
		k.addEntity("buildings", "system")
		k.addEntity("lighting", "system")
		k.relate("roads", "depends_on", "terrain")
		k.relate("buildings", "depends_on", "roads")
		k.relate("lighting", "depends_on", "buildings")
		a:ok(not k.hasRelation("lighting", "depends_on", "terrain"))
		local added = k.addRule("depends_on", "transitive") and k.infer(4)
		a:gt(added, 0)
		a:ok(k.hasRelation("lighting", "depends_on", "terrain"), "closure must be derived")
		local _, inferred = k.hasRelation("lighting", "depends_on", "terrain")
		a:ok(inferred, "a derived edge must be marked as derived")
		local path = k.path("lighting", "terrain")
		a:ok(path ~= nil)
		a:gte(#path, 2)
		a:equal(#k.query({ type = "system" }), 4)
	end)

	s:it("knowledge embeds entities and ranks similarity", function(a)
		local k = Kits.create("knowledge", { id = "k2", dims = 16 })
		k.addEntity("oak", "tree", { biome = "forest" })
		k.addEntity("pine", "tree", { biome = "forest" })
		k.addEntity("crane", "machine", { biome = "city" })
		k.relate("oak", "near", "pine")
		local sameKind = k.similarity("oak", "pine")
		local otherKind = k.similarity("oak", "crane")
		a:gt(sameKind, otherKind, "same-type entities must be closer")
		local nearest = k.nearest("oak", 1)
		a:equal(nearest[1].id, "pine")
		a:ok(k.forget("crane"))
		a:equal(k.stats().entities, 2)
	end)

	s:it("workflow orders, verifies, retries and rolls back", function(a)
		local w = Kits.create("workflow", { id = "w", maxRetries = 2 })
		local log = {}
		w.addStep("c", { requires = { "b" }, cost = 1,
			run = function() log[#log + 1] = "c" return true end,
			verify = function() return true end })
		w.addStep("a", { cost = 2, run = function() log[#log + 1] = "a" return true end })
		w.addStep("b", { requires = { "a" }, cost = 1,
			run = function() log[#log + 1] = "b" return true end,
			undo = function() log[#log + 1] = "undo-b" end })
		local order = w.plan()
		a:equal(order[1], "a")
		a:equal(order[3], "c")
		local ok = w.run({})
		a:ok(ok)
		a:equal(table.concat(log, ","), "a,b,c")
		a:near(w.progress(), 1, 1e-9)
		a:equal(w.estimate(), 4)

		local flaky = Kits.create("workflow", { id = "w2", maxRetries = 3 })
		local attempts = 0
		flaky.addStep("shaky", { run = function()
			attempts = attempts + 1
			return attempts
		end, verify = function() return attempts >= 3 end })
		a:ok(flaky.run({}))
		a:equal(attempts, 3, "the step must be retried until verification passes")

		local doomed = Kits.create("workflow", { id = "w3", maxRetries = 0 })
		local undone = 0
		doomed.addStep("good", { run = function() return true end,
			undo = function() undone = undone + 1 end })
		doomed.addStep("bad", { requires = { "good" }, run = function() return true end,
			verify = function() return false end })
		local ranOk, failedAt = doomed.run({})
		a:ok(not ranOk)
		a:equal(failedAt, "bad")
		a:equal(undone, 1, "a failed workflow must undo what it already did")
	end)

	s:it("critic scores against direction and names the worst offender", function(a)
