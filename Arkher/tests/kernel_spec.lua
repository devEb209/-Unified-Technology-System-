		Promise.resolve(2):andThen(function(v) return v * 3 end):andThen(function(v) value = v end)
		a:equal(value, 6)
		local caught
		Promise.reject("bad"):catch(function(e) caught = e end)
		a:equal(caught, "bad")
	end)
	s:it("all/race resolve", function(a)
		local out
		Promise.all({ Promise.resolve(1), Promise.resolve(2) }):andThen(function(v) out = v end)
