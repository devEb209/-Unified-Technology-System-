		a:near(g.toneCurve(1), 0.5, 1e-9)
	end)

	s:it("reality resolves layers by priority and commits a proposal", function(a)
		local r = Kits.create("reality", { id = "r" })
		r.installStack()
		r.set("authored", "city.population", 100)
		a:equal(r.get("city.population"), 100)
		r.set("simulated", "city.population", 140)
		local value, from = r.get("city.population")
		a:equal(value, 140)
		a:equal(from, "simulated")
		r.set("proposed", "city.population", 500)
		a:equal(r.get("city.population"), 500)
		a:equal(r.discard("proposed"), 1, "a discarded proposal must leave nothing behind")
		a:equal(r.get("city.population"), 140)
		r.set("proposed", "city.population", 200)
		a:equal(r.commit("proposed", "authored"), 1)
		a:equal(r.get("city.population"), 140, "simulated still wins over authored")
		a:gt(r.divergence("authored"), 0, "the simulation has pulled reality off the authored value")
		r.setEnabled("simulated", false)
		a:equal(r.get("city.population"), 200)
		a:near(r.divergence("authored"), 0, 1e-9, "with the simulation off, reality is the authored truth")
		a:equal(#r.keys(), 1)
	end)

