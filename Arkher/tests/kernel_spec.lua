		local data = { name = "arkher", version = 1, nested = { list = { 1, 2, 3 }, flag = true } }
		local decoded = Ser.decodeJSON(Ser.encodeJSON(data))
		a:equal(decoded.nested.list[3], 3)
		a:equal(decoded.name, "arkher")
	end)
	s:it("binary round trips and diffs", function(a)
		local data = { a = 1, b = "two", c = { 3.5, true } }
		local decoded = Ser.decodeBinary(Ser.encodeBinary(data))
		a:deepEqual(decoded, data)
		local d = Ser.diff({ x = 1, y = 2 }, { x = 5, y = 2 })
		a:equal(d.set.x, 5)
		local target = { x = 1, y = 2 }
		Ser.applyDiff(target, d)
		a:equal(target.x, 5)
	end)
end)

